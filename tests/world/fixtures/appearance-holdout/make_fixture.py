"""Write a tiny non-photographic test job to a new directory. Masks are hand-specified pixel grids."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3]))
from robotics.world_worker import camera_frames as cf

CASES = {'original': [0, 1, 2, 3], 'correct': [0, 1, 2, 3], 'incomplete': [0, 1], 'floor': [0, 1, 2, 3, 4],
         'background': [0, 1, 2, 3, 5], 'occluded': [6, 7, 8, 9], 'ignored': [0, 1, 2, 3, 10]}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path, data):
    path.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')


def make(root, case='correct', kind='ply', orientation='identity'):
    root.mkdir(parents=True, exist_ok=False)
    output = root / 'output'
    output.mkdir()
    coords = [(-0.0, 0, 2), (float('nan'), 0, 2), (1, 0, 2), (0, 1, 2), (1, 1, 2),
              (0, 2, 2), (2, 0, 2), (0, 0, 4), (-1, 0, -2), (40, 0, 2), (0, 0, 2), (-1, 0, 2)]
    cloud = output / 'fixture.ply'
    cloud.write_text(f'ply\nformat ascii 1.0\nelement vertex {len(coords)}\n'
                     'property float x\nproperty float y\nproperty float z\nend_header\n'
                     + ''.join(f'{x} {y} {z}\n' for x, y, z in coords), encoding='ascii')
    source = cloud
    if kind == 'splat':
        source = root / 'fixture.splat'
        source.write_bytes(b''.join(struct.pack('<6f8B', *row, .1, .1, .1, 12, 45, 80, 255, 255, 128, 128, 128)
                                    for row in coords))
    images = root / 'images'
    images.mkdir()
    frames, bindings, sources = [], [], []
    for i in range(2):
        # Two fixed labelled 9x7 views. Neither mask is generated by the scorer.
        mask = Image.new('L', (9, 7), 0)
        mask.paste(2, (0, 4, 9, 7))
        mask.paste(1, (3 + i, 2, 5 + i, 4))
        mask.putpixel((2 + i, 2), 255)
        mask_path = root / f'labels-{i}.png'
        mask.save(mask_path)
        image_path = images / f'authored-{i}.png'
        image = Image.new('RGB', mask.size, (60, 90, 110 + i))
        image.paste((170, 130, 50), (3 + i, 2, 5 + i, 4))
        image.save(image_path)
        camera = {'model': 'PINHOLE', 'params': [2, 2, 3, 2], 'pixelConvention': 'integer-centres'}
        pose = [[1, 0, 0, i], [0, 1, 0, 0], [0, 0, 1, 0]]
        raster = cf.file_record(root, image_path, width=9, height=7)
        sources.append({'name': image_path.name, 'kind': 'image', 'sha256': raster['sha256']})
        frame_id = cf.frame_id(raster['sha256'], raster['sha256'], camera, pose)
        frames.append({'frame_id': frame_id, 'image': raster, 'camera': camera, 'cam_from_world': pose,
                       'timestamp': None, 'origin': {'sourceIndex': i, 'sourceWidth': 9, 'sourceHeight': 7,
                       'exifOrientation': 1, 'sourceToFramePixelCenter': [[1, 0, 0], [0, 1, 0], [0, 0, 1]]}})
        bindings.append({'frameId': frame_id, 'mask': mask_path.name, 'maskSha256': sha(mask_path)})
    reconstruction = output / 'reconstruction.json'
    write_json(reconstruction, {'sources': sources})
    ledger = cf.write(root, {'schema': cf.SCHEMA, 'sources': sources, 'metric_verified': False, 'frames': frames,
                      'clouds': [cf.file_record(root, cloud, coordinate_frame='colmap')],
                      'reconstruction': cf.file_record(root, reconstruction)})
    labels = root / 'labels.json'
    write_json(labels, {'schema': 'brainsnn.appearance-holdout.v1', 'captureKind': 'authored-fixture',
               'cameraLedger': {'name': ledger.relative_to(root).as_posix(), 'sha256': sha(ledger)},
               'sourceSha256': sha(source), 'cameraCloudSha256': sha(cloud), 'target': 'Fixture chair',
               'selectionOperator': 'fixture selection',
               'labelReviewer': 'fixture reference grid', 'selectionFrameIds': [], 'frames': bindings,
               'reviewProtocol': 'blind-image-labels-held-out-from-selection-and-tuning'})
    subprocess.run(['node', str(HERE / 'make_edits.mjs'), str(source), str(root),
                    json.dumps(CASES[case]), orientation, case], check=True)
    return dict(job=root, labels_path=labels, source=source, edits=root / 'appearance-object-edits.json',
                variant=root / 'authored-variant.ply', receipt=root / 'appearance-object-variant-receipt.json',
                object_id='object-000001')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--case', choices=CASES, default='correct')
    parser.add_argument('--kind', choices=['ply', 'splat'], default='ply')
    parser.add_argument('--orientation', choices=['identity', 'flip-y-z'], default='identity')
    args = parser.parse_args()
    make(args.directory.resolve(), args.case, args.kind, args.orientation)
