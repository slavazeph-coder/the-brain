/** Fit a radial velocity controller on simulated waypoint demonstrations and evaluate complete held-out runs. */
import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {parseArgs} from 'node:util';
import {pathToFileURL, fileURLToPath} from 'node:url';
import {buildShowroomEpisodeScene,runShowroomEpisode,limitShowroomVelocity} from '../../brainsnn-r3f-app/public/world/showroom-episode-physics.mjs';
import {createShowroomExample,parseShowroomBundle} from '../../brainsnn-r3f-app/public/world/showroom-model.mjs';
import {imitationVelocity,radialFeatures} from '../../brainsnn-r3f-app/public/world/showroom-episode-policy.mjs';

const world = new URL('../../brainsnn-r3f-app/public/world/', import.meta.url);
const appRequire = createRequire(new URL('../../brainsnn-r3f-app/package.json', import.meta.url));
const {default:loadMuJoCo} = await import(pathToFileURL(appRequire.resolve('@mujoco/mujoco')));
const {values} = parseArgs({options:{
  'write-model':{type:'boolean'}, report:{type:'string'}, room:{type:'string'}
}});
const physics = await loadMuJoCo();
const sha = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const knots = [0, .025, .05, .1, .2, .4, .8, 1.6, 3.2, 6.4];
const ridge = .0001;

// Routes, corridor sizes and waypoint spacing are assigned by seed before fitting. Each run has its own room title.
function workshop(seed, blocked=false) {
  const knots = Array.from({length:5 + seed % 3}, (_, i) => {
    const t = i / (4 + seed % 3);
    const x = 1 + t * (6 + seed % 9);
    const z = 3.5 + Math.sin((1 + seed%3) * Math.PI*t + seed*.29) * (1 + seed%4 * .2);
    return [seed%2 ? 18-x : x, seed%4 ? z : 8-z].map(value=>Number(value.toFixed(6)));
  });
  const spacing = [.065,.15,.38,.85,1.65,3.3,6.6][seed%7];
  const points = [knots[0]];
  for (let i = 1; i < knots.length; i++) {
    const a = knots[i-1], b = knots[i];
    const pieces = Math.ceil(Math.hypot(b[0]-a[0],b[1]-a[1])/spacing);
    for (let j=1;j<=pieces;j++) points.push(a.map((v,k)=>Number((v+(b[k]-v)*j/pieces).toFixed(6))));
  }
  const shelf = blocked ? knots[2] : [8.5,.8];
  const [x,z] = shelf;
  const comparison = {objectId:'shelf',before:{points},after:{points}};
  const room = {title:'Delivery room '+seed,provenance:'Authored workshop delivery route '+seed,
    bounds:[0,0,18,8],routes:comparison,unknown:[],
    objects:[{id:'shelf',label:'Shelf',polygon:[[x-.4,z-.3],[x+.4,z-.3],[x+.4,z+.3],[x-.4,z+.3]]}]};
  return buildShowroomEpisodeScene(room);
}

// Positive definite ridge normal matrix, solved with pivoting for knots absent in a batch.
function solve(matrix, target) {
  const rows = matrix.map((row,i) => [...row,target[i]]);
  for (let i=0; i<rows.length; i++) {
    let pivot=i;
    for(let j=i+1;j<rows.length;j++) if(Math.abs(rows[j][i])>Math.abs(rows[pivot][i])) pivot=j;
    [rows[i],rows[pivot]]=[rows[pivot],rows[i]];
    const denominator=rows[i][i];
    for(let k=i;k<=rows.length;k++) rows[i][k]/=denominator;
    for(let j=0;j<rows.length;j++) {
      if(j===i) continue;
      const multiplier=rows[j][i];
      for(let k=i;k<=rows.length;k++) rows[j][k]-=multiplier*rows[i][k];
    }
  }
  return rows.map(row=>row.at(-1));
}

const seeds = Array.from({length:21},(_,i)=>i+1);
const matrix = knots.map((_,i)=>knots.map((__,j)=>i===j ? ridge : 0));
const target = knots.map(()=>0);
const trainingInputs = [];
let transitions=0;
for (const seed of seeds) {
  const episode = await runShowroomEpisode(physics,workshop(seed));
  // Quantize recorded signals to six decimal places for a stable training receipt across Node builds.
  const records = episode.frames.map(f => [f.time,...f.position,...f.velocity,...f.target,...(f.action??[])].map(v=>Math.round(v*1e6)));
  trainingInputs.push({sceneSha256:episode.sceneSha256,teacherSha256:sha(records)});
  for (const {position,target:waypoint,action} of episode.frames) {
    if(!action) continue;
    const dx=waypoint[0]-position[0], dz=waypoint[1]-position[1], radius=Math.hypot(dx,dz);
    if(!radius) continue;
    const features=radialFeatures(radius,knots);
    const along=(action[0]*dx+action[1]*dz)/radius;
    for(let i=0;i<knots.length;i++) {
      target[i]+=features[i]*along;
      for(let j=0;j<knots.length;j++) matrix[i][j]+=features[i]*features[j];
    }
    transitions++;
  }
}
const weights=solve(matrix,target).map(v=>Number(v.toFixed(10)));
const fields={kind:'radial-velocity-ridge-v1',knots,weights,ridge,trainingScenes:seeds.length,
  trainingTransitions:transitions,engineVersion:physics.mj_versionString(),trainingSha256:sha(trainingInputs)};
const driver={id:'showroom-driver-'+sha(fields).slice(0,16),...fields};
const path=fileURLToPath(new URL('assets/showroom-driver.mjs',world));
const encoded='// Generated by scripts/world-demo/fit_showroom_driver.mjs --write-model\nexport const showroomDriver = '+JSON.stringify(driver,null,2)+';\n';
if(values['write-model']) await writeFile(path,encoded);
else if (await readFile(path,'utf8')!==encoded) throw Error('Generated coefficients differ from the bundled driver.');

const heldOut=[];
for (const seed of [43,54,62,75,81,97]) heldOut.push(workshop(seed));
for (const seed of [53,66]) heldOut.push(workshop(seed,true));
function addRoom(room) {
  for (const pair of [room.routes,...(room.comparisons??[])]) {
    for(const variant of ['before','after']) heldOut.push(buildShowroomEpisodeScene(room,{objectId:pair.objectId,variant}));
  }
}
addRoom(createShowroomExample());
if(values.room) addRoom(parseShowroomBundle(await readFile(values.room,'utf8')));
const cases=[];
for(const scene of heldOut) {
  const teacher=await runShowroomEpisode(physics,scene);
  if(trainingInputs.some(input=>input.sceneSha256===teacher.sceneSha256)) throw Error('Training and test scene overlap.');
  const imitation=await runShowroomEpisode(physics,scene,{controller:'imitation',trainingId:driver.id,
    act:observation=>imitationVelocity(driver,observation)});
  const stationary=await runShowroomEpisode(physics,scene,{controller:'stationary'});
  let squaredError=0;
  for(const f of teacher.frames) {
    if(!f.action) continue;
    const proposal=limitShowroomVelocity(imitationVelocity(driver,f));
    squaredError+=(proposal[0]-f.action[0])**2+(proposal[1]-f.action[1])**2;
  }
  const score=ep=>({...ep.score,seconds:ep.frames.at(-1).time,observations:ep.frames.length});
  cases.push({room:scene.title,objectId:scene.objectId,variant:scene.variant,sceneSha256:teacher.sceneSha256,
    teacherActionRmseMps:Math.sqrt(squaredError/(2*(teacher.frames.length-1))),waypoint:score(teacher),imitation:score(imitation),stationary:score(stationary)});
}
const report={schema:'brainsnn.showroom-driver-evaluation.v1',driver,trainingInputs,cases};
if(values.report) await writeFile(values.report,JSON.stringify(report,null,2)+'\n');
console.log(driver.id,transitions,'training transitions in',seeds.length,'rooms');
console.table(cases.map(c=>({room:c.room,variant:c.variant,object:c.objectId,waypoint:c.waypoint.reason,
  imitation:c.imitation.reason,stationary:c.stationary.reason,actionRmse:c.teacherActionRmseMps.toFixed(5)})));
